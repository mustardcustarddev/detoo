import { defineCollection } from 'astro:content';
import { z } from 'astro/zod';
import { glob } from 'astro/loaders';
import { SITE } from './lib/site';

/** Blog posts: thought leadership on decision-making tools in software teams. */
const blog = defineCollection({
  loader: glob({ pattern: '**/*.{md,mdx}', base: './src/content/blog' }),
  schema: ({ image }) =>
    z.object({
      title: z.string(),
      description: z
        .string()
        .max(160, 'Descriptions are shown in search results: keep them to 160 characters'),
      pubDate: z.coerce.date(),
      updatedDate: z.coerce.date().optional(),
      heroImage: image().optional(),
      author: z.string().default('tom-regan'),
      tags: z.array(z.string()).default([]),
      draft: z.boolean().default(false),
      /** The tool the post is about, which its call to action points to. */
      tool: z.enum(SITE.tools).optional(),
      canonicalUrl: z.url().optional(),
      noindex: z.boolean().default(false),
    }),
});

/** Hand-written documentation: getting started, release notices, guides and agent skills. */
const docs = defineCollection({
  loader: glob({ pattern: '**/*.{md,mdx}', base: './src/content/docs' }),
  schema: z.object({
    title: z.string(),
    description: z
      .string()
      .max(160, 'Descriptions are shown in search results: keep them to 160 characters'),
    section: z.enum(['getting-started', 'releases', 'guides', 'skills']),
    order: z.number(),
  }),
});

/**
 * The command reference: one page per tool and per command, saying what the
 * tool's help says, as Markdown.  Generated by tools/sitegen; never edit it.
 */
const reference = defineCollection({
  loader: glob({ pattern: '**/*.md', base: './src/content/reference' }),
  schema: z.object({
    tool: z.enum(SITE.tools),
    command: z.string(),
    title: z.string(),
    description: z.string(),
    order: z.number(),
  }),
});

/** The people who write the posts.  Only the name is required. */
const authors = defineCollection({
  loader: glob({ pattern: '**/*.json', base: './src/content/authors' }),
  schema: z.object({
    name: z.string(),
    role: z.string().optional(),
    bio: z.string().optional(),
    url: z.url().optional(),
  }),
});

export const collections = { docs, reference, blog, authors };
